"""ATT&CK Navigator layers: what Kratos can detect, and what it has seen.

Layer file format 4.5 (attack-navigator `layers/spec/v4.5/layerformat.md`, the
current one as of Navigator v5.3.2), domain enterprise-attack, ATT&CK v19.

- coverage -- every technique a Kratos rule can label (score 1, comment = the
  rule ids). Only rules this build actually has (kratos.lifecycle.rules) count.
- observed -- techniques in the open or verified findings Kratos remembers for a
  machine (or every machine): scored by the worst severity, comment = finding
  keys. Decided (accepted, false positive, out of scope) and fixed findings are
  left out -- the layer shows what is still live.

Each annotation is pinned to the tactic(s) the label names, so a technique sits
in the right column (e.g. Defense Impairment, not every tactic it is listed under).
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable

from kratos.attack import attack_of
from kratos.attack.mapping import RULE_ATTACK, Behaviour
from kratos.attack.mapping import entry as _entry
from kratos.attack.table import major_version, table

LAYER_FORMAT = "4.5"
NAVIGATOR_VERSION = "5.3.2"
DOMAIN = "enterprise-attack"
PLATFORMS = ["Linux"]
SEVERITY_SCORE = {"info": 1, "low": 2, "medium": 3, "high": 4, "critical": 5}
_LAYOUT = {"layout": "side", "showID": True, "showName": True, "showAggregateScores": False,
           "countUnscored": False, "aggregateFunction": "max", "expandedSubtechniques": "annotated"}


def _base(name: str, description: str) -> dict[str, Any]:
    bundle = table()["bundle"]
    return {
        "name": name,
        "versions": {"attack": major_version(), "navigator": NAVIGATOR_VERSION, "layer": LAYER_FORMAT},
        "domain": DOMAIN,
        "description": description,
        "filters": {"platforms": list(PLATFORMS)},
        "sorting": 0,
        "layout": dict(_LAYOUT),
        "hideDisabled": False,
        "techniques": [],
        "showTacticRowBackground": False,
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
        "selectVisibleTechniques": False,
        "metadata": [{"name": "generated by", "value": "Kratos (kratos attack-layer)"},
                     {"name": "ATT&CK data", "value": f"{bundle['name']} (sha256 {bundle['sha256'][:16]}...)"}],
    }


def _cells(labels: Iterable[dict[str, Any]]) -> Iterable[tuple[str, str]]:
    """(technique id, tactic shortname) for every column a label sits in."""
    tactics = table()["tactics"]
    by_name = {v["name"]: k for k, v in tactics.items()}
    for lab in labels:
        tid = str(lab.get("technique_id") or "")
        if not tid:
            continue
        shorts = [t.get("shortname") or by_name.get(t.get("name", "")) for t in lab.get("tactics") or []
                  if isinstance(t, dict)]
        if not shorts and lab.get("tactic") in by_name:   # a label written before A.3 (one tactic)
            shorts = [by_name[lab["tactic"]]]
        for short in shorts:
            if short in tactics:
                yield tid, short


def _ordered(cells: dict[tuple[str, str], Any]) -> list[tuple[str, str]]:
    order = {k: v["order"] for k, v in table()["tactics"].items()}
    return sorted(cells, key=lambda c: (order.get(c[1], 99), c[0]))


def _with_parents(techniques: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """A sub-technique shows only under an expanded parent: add an unscored parent
    entry (showSubtechniques) for each annotated sub-technique's column."""
    have = {(t["techniqueID"], t["tactic"]) for t in techniques}
    parents = []
    for t in techniques:
        if "." in t["techniqueID"]:
            key = (t["techniqueID"].split(".")[0], t["tactic"])
            if key not in have:
                have.add(key)
                parents.append({"techniqueID": key[0], "tactic": key[1], "showSubtechniques": True,
                                "enabled": True})
    for t in techniques:
        if "." not in t["techniqueID"] and any(o["techniqueID"].startswith(t["techniqueID"] + ".")
                                               and o["tactic"] == t["tactic"] for o in techniques):
            t["showSubtechniques"] = True
    return techniques + parents


def coverage_layer(rule_ids: Iterable[str] | None = None) -> dict[str, Any]:
    """Techniques Kratos has a rule for. `rule_ids`: the rules this build has
    (default: kratos.lifecycle.rules.RULES)."""
    if rule_ids is None:
        from kratos.detect import pack as _packs
        from kratos.lifecycle.rules import RULES
        rule_ids = [*RULES, *(r.id for r in _packs.shipped().pack.rules)]   # + the shipped Sigma rules (C.1)
    wanted = set(rule_ids)
    cells: dict[tuple[str, str], set[str]] = {}
    for rid in sorted(wanted):
        entry = RULE_ATTACK.get(rid) or _entry(rid)
        if isinstance(entry, Behaviour):
            for cell in _cells(entry.labels):
                cells.setdefault(cell, set()).add(rid)
    techniques = [{"techniqueID": tid, "tactic": tac, "score": 1, "enabled": True,
                   "comment": "Kratos rules: " + ", ".join(sorted(cells[(tid, tac)])),
                   "metadata": [{"name": "rule", "value": r} for r in sorted(cells[(tid, tac)])]}
                  for tid, tac in _ordered(cells)]
    layer = _base("Kratos detection coverage",
                  f"Techniques at least one Kratos rule labels (ATT&CK v{table()['attack_version']}). "
                  "Covered means a rule can raise a finding labelled with it -- not that every "
                  "variant of the technique is caught.")
    layer["techniques"] = _with_parents(techniques)
    layer["gradient"] = {"colors": ["#ffffff", "#66b1ff"], "minValue": 0, "maxValue": 1}
    layer["legendItems"] = [{"label": "a Kratos rule can detect this", "color": "#66b1ff"}]
    return layer


def observed_layer(records: Iterable[dict[str, Any]], *, scope: str) -> dict[str, Any]:
    """Techniques in the given finding records (kratos.lifecycle.query rows with
    the latest finding dict under "finding"). The caller passes open/verified only."""
    cells: dict[tuple[str, str], dict[str, Any]] = {}
    for rec in records:
        finding = dict(rec.get("finding") or {})
        finding.setdefault("id", rec.get("rule_id"))
        finding.setdefault("entities", rec.get("entities") or [])
        sev = str(rec.get("severity") or finding.get("severity") or "info").lower()
        for cell in _cells(attack_of(finding)):
            c = cells.setdefault(cell, {"score": 0, "keys": []})
            c["score"] = max(c["score"], SEVERITY_SCORE.get(sev, 1))
            c["keys"].append(f"{rec.get('short_key') or str(rec.get('finding_key', ''))[:12]} "
                             f"{rec.get('rule_id')} on {rec.get('target')} ({sev}, {rec.get('state')})")
    techniques = [{"techniqueID": tid, "tactic": tac, "score": cells[(tid, tac)]["score"], "enabled": True,
                   "comment": "; ".join(cells[(tid, tac)]["keys"]),
                   "metadata": [{"name": "finding", "value": k} for k in cells[(tid, tac)]["keys"]]}
                  for tid, tac in _ordered(cells)]
    layer = _base(f"Kratos observed: {scope}",
                  f"Techniques in the open or verified findings Kratos remembers for {scope}, "
                  "scored by the worst severity (1 info .. 5 critical). Decided and fixed findings are left out.")
    layer["techniques"] = _with_parents(techniques)
    layer["gradient"] = {"colors": ["#ffe766", "#ff6666"], "minValue": 1, "maxValue": 5}
    layer["legendItems"] = [{"label": "worst severity info/low", "color": "#ffe766"},
                            {"label": "worst severity high/critical", "color": "#ff6666"}]
    return layer


def observed_records(data_dir: Path, target: str | None) -> list[dict[str, Any]]:
    """Open/verified finding records (+ their latest finding dict) for a machine,
    or every machine when target is None."""
    from kratos.lifecycle import query as Q

    out = []
    for row in Q.list_findings(data_dir, target=target, state="open_verified"):
        _rec, latest, _events = Q.get_finding(data_dir, row["finding_key"])
        out.append({**row, "finding": latest})
    return out
