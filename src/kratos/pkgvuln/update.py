"""`kratos vulndb-update`: download the vulnerability data and build the index.

The ONLY place Kratos asks the network for vulnerability data, and only when a
person runs it (or schedules it). Everything it sends is the name of a public
file -- an ecosystem export, an advisory id, a feed year. Never a package name or
version: the package list never leaves Kratos (tests/test_pkgvuln_privacy.py).

Sources:

- **OSV** (distribution advisories): ``<OSV_BASE>/<ecosystem>/all.zip``, or, when
  only a few advisories changed since the last build, ``modified_id.csv`` plus the
  changed ``<ecosystem>/<id>.json`` records. Checked against the object's MD5
  (``x-goog-hash``), a size cap, the zip's own CRCs, and a JSON parse.
- **CISA KEV**: the catalogue's JSON feed.
- **EPSS**: FIRST's daily ``epss_scores-current.csv.gz``.
- **NVD CVSS**: the yearly 2.0 feeds (the same downloader the network scan's CVE
  list uses), checked against each feed's published SHA-256; later updates apply
  the 8-day "modified" feed instead of re-reading every year.

The new index is built in ``vulndb.sqlite.tmp`` (a copy of the current one for an
incremental update), checked with ``PRAGMA integrity_check``, and swapped in with
one ``os.replace``. Any OSV failure, an interruption, or a failed check leaves the
previous index exactly as it was. KEV, EPSS and NVD are enrichment: if one of
them can't be fetched, its previous rows are kept and the result says which
source is stale.
"""
