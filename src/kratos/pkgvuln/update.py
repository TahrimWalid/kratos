# --------------------------------------------------------------------------- HTTP
def _session(session: Any) -> Any:
    if session is not None:
        return session
    import requests

    s = requests.Session()
    s.headers["User-Agent"] = "kratos-vulndb-update"
    return s


def _md5_from_header(headers: Any) -> bytes | None:
    """The object's MD5 from Google Cloud Storage's x-goog-hash header, if present."""
    raw = ""
    try:
        raw = headers.get("x-goog-hash") or ""
    except AttributeError:
        return None
    for part in str(raw).split(","):
        k, _, v = part.strip().partition("=")
        if k == "md5" and v:
            try:
                return base64.b64decode(v + "=" * (-len(v) % 4))
            except (ValueError, TypeError):
                return None
    return None


@dataclass
class Fetched:
    status: int               # 200, or 304 for "not modified"
    path: Path | None
    etag: str = ""
    last_modified: str = ""
    size: int = 0


def _fetch(session: Any, url: str, dest: Path, max_bytes: int, *, etag: str = "",
           check_md5: bool = False) -> Fetched:
    """Stream `url` to `dest` (at most `max_bytes`). With `etag`, a 304 means the
    previous copy is still current. Raises UpdateError on anything else."""
    import requests

    headers = {"If-None-Match": etag} if etag else {}
    try:
        with session.get(url, stream=True, timeout=HTTP_TIMEOUT, headers=headers) as resp:
            if resp.status_code == 304:
                return Fetched(304, None, etag)
            if resp.status_code != 200:
                raise UpdateError(f"{url}: HTTP {resp.status_code}")
            declared = resp.headers.get("content-length")
            if declared and declared.isdigit() and int(declared) > max_bytes:
                raise UpdateError(f"{url}: larger than expected ({int(declared)} bytes), not downloaded")
            want_md5 = _md5_from_header(resp.headers) if check_md5 else None
            md5 = hashlib.md5()
            size = 0
            with dest.open("wb") as fh:
                for chunk in resp.iter_content(chunk_size=1 << 16):
                    size += len(chunk)
                    if size > max_bytes:
                        raise UpdateError(f"{url}: larger than expected, download stopped")
                    md5.update(chunk)
                    fh.write(chunk)
            # Content-Length counts the bytes on the wire; with a content encoding
            # (gzip) requests hands over the decoded bytes, so only compare plain bodies.
            encoded = str(resp.headers.get("content-encoding") or "identity").lower() not in ("", "identity")
            if declared and declared.isdigit() and not encoded and int(declared) != size:
                raise UpdateError(f"{url}: download ended early ({size} of {declared} bytes)")
            if want_md5 is not None and md5.digest() != want_md5:
                raise UpdateError(f"{url}: the download does not match the server's checksum")
            return Fetched(200, dest, str(resp.headers.get("etag") or ""),
                           str(resp.headers.get("last-modified") or ""), size)
    except requests.RequestException as e:
        raise UpdateError(f"{url}: {e.__class__.__name__} (no network?)") from None
    except OSError as e:
        raise UpdateError(f"{url}: could not write the download ({e.strerror or e})") from None


# --------------------------------------------------------------------------- OSV records -> rows
def record_cves(rec: dict[str, Any]) -> list[str]:
    """The CVE ids an OSV record is about: its own id, aliases, upstream and related
    (a USN lists its per-CVE records there as UBUNTU-CVE-..., AlmaLinux its CVEs)."""
    out: set[str] = set()
    for value in [rec.get("id"), *(rec.get("aliases") or []), *(rec.get("upstream") or []),
                  *(rec.get("related") or [])]:
        m = _CVE_RE.match(str(value or "").strip())
        if m:
            out.add(m.group(1).upper())
    return sorted(out)


def _intervals(events: list[dict[str, Any]]) -> list[tuple[str, str | None, str | None]]:
    """OSV range events -> (introduced, fixed, last_affected) intervals, in the
    order the advisory lists them (introduced, then the fix that closes it)."""
    out: list[tuple[str, str | None, str | None]] = []
    intro: str | None = None
    for ev in events or []:
        if not isinstance(ev, dict):
            continue
        if "introduced" in ev:
            if intro is not None:
                out.append((intro, None, None))
            intro = str(ev["introduced"])
        elif "fixed" in ev:
            out.append((intro if intro is not None else "0", str(ev["fixed"]), None))
            intro = None
        elif "last_affected" in ev:
            out.append((intro if intro is not None else "0", None, str(ev["last_affected"])))
            intro = None
    if intro is not None:
        out.append((intro, None, None))
    return out


def _record_severity(rec: dict[str, Any], top: str) -> str:
    for s in rec.get("severity") or []:
        if isinstance(s, dict) and s.get("type") == "Ubuntu" and s.get("score"):
            return str(s["score"]).lower()
    if top in ("Rocky Linux", "AlmaLinux", "Red Hat"):
        m = _RPM_SEVERITY_RE.match(str(rec.get("summary") or ""))
        if m:
            return m.group(1).lower()
    return ""


def _affected_severity(a: dict[str, Any]) -> str:
    es = a.get("ecosystem_specific") if isinstance(a.get("ecosystem_specific"), dict) else {}
    for key in ("urgency", "ubuntu_priority", "severity"):
        if es.get(key):
            return str(es[key]).lower()
    return ""


class _Writer:
    """Applies OSV records to an open index connection, keeping only the releases
    the selectors want."""

    def __init__(self, conn: sqlite3.Connection, selectors: list[Selector]):
        self.conn = conn
        self.selectors = selectors
        self._eco: dict[str, int | None] = {}

    def _eco_id(self, name: str) -> int | None:
        if name in self._eco:
            return self._eco[name]
        sel = next((s for s in self.selectors if s.matches(name)), None)
        if sel is None:
            self._eco[name] = None
            return None
        self.conn.execute("INSERT OR IGNORE INTO ecosystems (name, selector) VALUES (?, ?)", (name, sel.key))
        eid = int(self.conn.execute("SELECT id FROM ecosystems WHERE name = ?", (name,)).fetchone()[0])
        self._eco[name] = eid
        return eid

    def remove(self, top: str, osv_id: str) -> None:
        row = self.conn.execute("SELECT id FROM advisories WHERE top = ? AND osv_id = ?", (top, osv_id)).fetchone()
        if row is not None:
            aid = row[0]
            for table in ("ranges", "versions", "advisory_cves"):
                self.conn.execute(f"DELETE FROM {table} WHERE advisory = ?", (aid,))
            self.conn.execute("DELETE FROM advisories WHERE id = ?", (aid,))
        self.conn.execute("DELETE FROM precise_cves WHERE top = ? AND osv_id = ?", (top, osv_id))

    def apply(self, top: str, rec: dict[str, Any]) -> bool:
        """Store `rec` (replacing any earlier version of it). True when it says
        something about a wanted release."""
        osv_id = str(rec.get("id") or "")
        if not _OSV_ID_RE.fullmatch(osv_id):
            return False
        self.conn.execute("INSERT OR REPLACE INTO seen (top, osv_id, modified) VALUES (?, ?, ?)",
                          (top, osv_id, str(rec.get("modified") or "")))
        self.remove(top, osv_id)
        if rec.get("withdrawn") or osv_id.startswith(_NON_SECURITY_PREFIXES):
            return False
        cves = record_cves(rec)
        if not cves:
            return False
        if _PRECISE_RE.match(osv_id):
            self.conn.executemany("INSERT INTO precise_cves (top, osv_id, cve) VALUES (?, ?, ?)",
                                  [(top, osv_id, c) for c in cves])
        rec_sev = _record_severity(rec, top)
        ranges: list[tuple[Any, ...]] = []
        versions: list[tuple[Any, ...]] = []
        for a in rec.get("affected") or []:
            if not isinstance(a, dict) or not isinstance(a.get("package"), dict):
                continue
            eid = self._eco_id(str(a["package"].get("ecosystem") or ""))
            name = str(a["package"].get("name") or "")
            if eid is None or not name:
                continue
            sev = _affected_severity(a) or None
            eco_ranges = [r for r in a.get("ranges") or [] if isinstance(r, dict) and r.get("type") == "ECOSYSTEM"]
            for r in eco_ranges:
                for intro, fixed, last in _intervals(r.get("events") or []):
                    ranges.append((eid, name, intro, fixed, last, sev))
            if not eco_ranges:
                for v in a.get("versions") or []:
                    if isinstance(v, str) and v:
                        versions.append((eid, name, v, sev))
        if not ranges and not versions:
            return False
        cur = self.conn.execute(
            "INSERT INTO advisories (osv_id, top, modified, published, summary, distro_severity, precise) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            (osv_id, top, str(rec.get("modified") or ""), str(rec.get("published") or ""),
             str(rec.get("summary") or "")[:300], rec_sev, 1 if _PRECISE_RE.match(osv_id) else 0))
        aid = cur.lastrowid
        self.conn.executemany("INSERT INTO ranges (advisory, ecosystem, package, introduced, fixed, last_affected, "
                              "distro_severity) VALUES (?, ?, ?, ?, ?, ?, ?)", [(aid, *r) for r in ranges])
        self.conn.executemany("INSERT INTO versions (advisory, ecosystem, package, version, distro_severity) "
                              "VALUES (?, ?, ?, ?, ?)", [(aid, *v) for v in versions])
        self.conn.executemany("INSERT INTO advisory_cves (advisory, cve) VALUES (?, ?)", [(aid, c) for c in cves])
        return True

    def note_unparsed(self, top: str, osv_id: str, modified: str) -> None:
        """An advisory that names none of the wanted releases. Only remembered as seen
        -- and, for a per-CVE record, as "this CVE has a record that skips the wanted
        releases" (its id carries the CVE, so it need not be parsed)."""
        self.conn.execute("INSERT OR REPLACE INTO seen (top, osv_id, modified) VALUES (?, ?, ?)", (top, osv_id, modified))
        self.remove(top, osv_id)
        m = _CVE_RE.match(osv_id)
        if m and _PRECISE_RE.match(osv_id):
            self.conn.execute("INSERT INTO precise_cves (top, osv_id, cve) VALUES (?, ?, ?)", (top, osv_id, m.group(1)))

    def clear_top(self, top: str) -> None:
        ids = [r[0] for r in self.conn.execute("SELECT id FROM advisories WHERE top = ?", (top,))]
        for chunk in range(0, len(ids), 500):
            part = ids[chunk:chunk + 500]
            marks = ",".join("?" * len(part))
            for table in ("ranges", "versions", "advisory_cves"):
                self.conn.execute(f"DELETE FROM {table} WHERE advisory IN ({marks})", part)
        self.conn.execute("DELETE FROM advisories WHERE top = ?", (top,))
        self.conn.execute("DELETE FROM seen WHERE top = ?", (top,))
        self.conn.execute("DELETE FROM precise_cves WHERE top = ?", (top,))


def _iter_zip_records(path: Path, markers: list[bytes]) -> Iterator[tuple[str, bytes | None]]:
    """(member name, raw JSON or None when it mentions none of the wanted releases).
    Reading each member checks its CRC; a broken zip raises UpdateError."""
    try:
        with zipfile.ZipFile(path) as zf:
            for info in zf.infolist():
                if info.is_dir() or not info.filename.endswith(".json"):
                    continue
                if info.file_size > OSV_RECORD_MAX_BYTES:
                    raise UpdateError(f"{info.filename}: larger than any advisory should be")
                raw = zf.read(info)
                yield info.filename, (raw if any(m in raw for m in markers) else None)
    except (zipfile.BadZipFile, zipfile.LargeZipFile, OSError, EOFError) as e:
        raise UpdateError(f"the downloaded export is not a valid zip ({e})") from None


def _osv_id_from_member(name: str) -> str:
    return name.rsplit("/", 1)[-1][:-len(".json")]


def _parse_record(raw: bytes, where: str) -> dict[str, Any]:
    try:
        rec = json.loads(raw)
    except ValueError:
        raise UpdateError(f"{where}: not valid JSON") from None
    if not isinstance(rec, dict) or not isinstance(rec.get("id"), str):
        raise UpdateError(f"{where}: not an OSV record")
    return rec


# --------------------------------------------------------------------------- OSV per top-level ecosystem
def _osv_url(top: str, name: str) -> str:
    return f"{OSV_BASE}/{quote(top)}/{quote(name)}"


def _update_osv_full(conn: sqlite3.Connection, session: Any, top: str, sels: list[Selector], work: Path,
                     log: Log) -> str:
    dest = work / f"{top.replace(' ', '_')}.zip"
    log(f"  OSV {top}: downloading the full export ...")
    got = _fetch(session, _osv_url(top, "all.zip"), dest, OSV_ZIP_MAX_BYTES, check_md5=True)
    writer = _Writer(conn, sels)
    markers = [s.raw_marker for s in sels]
    writer.clear_top(top)
    kept = parsed = 0
    for name, raw in _iter_zip_records(dest, markers):
        osv_id = _osv_id_from_member(name)
        if raw is None:
            if _OSV_ID_RE.fullmatch(osv_id):
                writer.note_unparsed(top, osv_id, "")
            continue
        rec = _parse_record(raw, f"{top}/{name}")
        parsed += 1
        kept += writer.apply(top, rec)
    _note_seen_modified(conn, session, top, work)
    dest.unlink(missing_ok=True)
    _set_meta(conn, f"osv:{top}", rows=kept, detail=f"full export, {got.size} bytes, {parsed} relevant records")
    return f"full export: {kept} advisories kept for {', '.join(s.key for s in sels)}"


def _modified_index(session: Any, top: str, work: Path, etag: str = "") -> tuple[Fetched, dict[str, str]]:
    dest = work / f"{top.replace(' ', '_')}.modified_id.csv"
    got = _fetch(session, _osv_url(top, "modified_id.csv"), dest, OSV_INDEX_MAX_BYTES, etag=etag, check_md5=True)
    if got.status == 304:
        return got, {}
    out: dict[str, str] = {}
    with dest.open(encoding="utf-8", errors="replace") as fh:
        for line in fh:
            stamp, _, osv_id = line.strip().partition(",")
            osv_id = osv_id.rsplit("/", 1)[-1]
            if stamp and _OSV_ID_RE.fullmatch(osv_id):
                out[osv_id] = stamp
    dest.unlink(missing_ok=True)
    if not out:
        raise UpdateError(f"OSV {top}: the modification index is empty")
    return got, out


def _note_seen_modified(conn: sqlite3.Connection, session: Any, top: str, work: Path) -> None:
    """After a full export, record each advisory's modification time from the
    modification index, so the next update can fetch only what changed. Best
    effort: without it the next update simply downloads the export again."""
    try:
        got, mod = _modified_index(session, top, work)
    except UpdateError:
        conn.execute("DELETE FROM meta WHERE source = ?", (f"osv-index:{top}",))
        return
    conn.executemany("UPDATE seen SET modified = ? WHERE top = ? AND osv_id = ?",
                     [(stamp, top, osv_id) for osv_id, stamp in mod.items()])
    _set_meta(conn, f"osv-index:{top}", rows=len(mod), etag=got.etag)


def _update_osv_incremental(conn: sqlite3.Connection, session: Any, top: str, sels: list[Selector], work: Path,
                            log: Log) -> str | None:
    """Fetch only the advisories changed since the last build. None when a full
    export is needed instead (too many changes, or no usable earlier state)."""
    row = conn.execute("SELECT etag FROM meta WHERE source = ?", (f"osv-index:{top}",)).fetchone()
    if row is None:
        return None
    got, mod = _modified_index(session, top, work, etag=row[0] or "")
    if got.status == 304:
        _touch_meta(conn, f"osv:{top}")
        return "unchanged"
    seen = {r[0]: r[1] or "" for r in conn.execute("SELECT osv_id, modified FROM seen WHERE top = ?", (top,))}
    changed = [i for i, stamp in mod.items() if seen.get(i) != stamp]
    removed = [i for i in seen if i not in mod]
    if len(changed) > INCREMENTAL_MAX_RECORDS:
        return None
    log(f"  OSV {top}: {len(changed)} changed advisories, {len(removed)} removed")
    writer = _Writer(conn, sels)
    markers = [s.raw_marker for s in sels]
    for osv_id in removed:
        writer.remove(top, osv_id)
        conn.execute("DELETE FROM seen WHERE top = ? AND osv_id = ?", (top, osv_id))
    dest = work / "record.json"
    for osv_id in changed:
        _fetch(session, _osv_url(top, f"{osv_id}.json"), dest, OSV_RECORD_MAX_BYTES, check_md5=True)
        raw = dest.read_bytes()
        if not any(m in raw for m in markers):
            writer.note_unparsed(top, osv_id, mod[osv_id])
            continue
        rec = _parse_record(raw, f"{top}/{osv_id}.json")
        writer.apply(top, rec)
        conn.execute("UPDATE seen SET modified = ? WHERE top = ? AND osv_id = ?", (mod[osv_id], top, osv_id))
    dest.unlink(missing_ok=True)
    _set_meta(conn, f"osv-index:{top}", rows=len(mod), etag=got.etag)
    kept = conn.execute("SELECT COUNT(*) FROM advisories WHERE top = ?", (top,)).fetchone()[0]
    _set_meta(conn, f"osv:{top}", rows=kept, detail=f"incremental: {len(changed)} changed, {len(removed)} removed")
    return f"{len(changed)} changed advisories fetched"


# --------------------------------------------------------------------------- KEV / EPSS / NVD
def _update_kev(conn: sqlite3.Connection, session: Any, work: Path) -> str:
    etag = _meta_etag(conn, "kev")
    dest = work / "kev.json"
    got = _fetch(session, KEV_URL, dest, KEV_MAX_BYTES, etag=etag)
    if got.status == 304:
        _touch_meta(conn, "kev")
        return "unchanged"
    try:
        data = json.loads(dest.read_text(encoding="utf-8"))
        items = data["vulnerabilities"]
        rows = [(str(v["cveID"]).upper(), v.get("dateAdded"), v.get("dueDate"), v.get("knownRansomwareCampaignUse"),
                 v.get("vendorProject"), v.get("product"), v.get("vulnerabilityName"))
                for v in items if isinstance(v, dict) and re.fullmatch(r"CVE-\d{4}-\d{4,}", str(v.get("cveID", "")))]
    except (ValueError, KeyError, TypeError) as e:
        raise UpdateError(f"the KEV catalogue is not in the expected shape ({e.__class__.__name__})") from None
    if len(rows) < 100:
        raise UpdateError(f"the KEV catalogue lists only {len(rows)} entries -- refusing it")
    conn.execute("DELETE FROM kev")
    conn.executemany("INSERT OR REPLACE INTO kev VALUES (?, ?, ?, ?, ?, ?, ?)", rows)
    _set_meta(conn, "kev", rows=len(rows), etag=got.etag, detail=str(data.get("catalogVersion") or ""))
    dest.unlink(missing_ok=True)
    return f"{len(rows)} exploited CVEs"


def _update_epss(conn: sqlite3.Connection, session: Any, work: Path) -> str:
    etag = _meta_etag(conn, "epss")
    dest = work / "epss.csv.gz"
    got = _fetch(session, EPSS_URL, dest, EPSS_MAX_BYTES, etag=etag)
    if got.status == 304:
        _touch_meta(conn, "epss")
        return "unchanged"
    rows: list[tuple[str, float, float, str]] = []
    score_date = ""
    try:
        with gzip.open(dest, "rt", encoding="utf-8") as fh:
            first = fh.readline()
            m = re.search(r"score_date:([0-9T:\-+Z.]+)", first)
            score_date = m.group(1)[:10] if m else ""
            header = first if not first.startswith("#") else fh.readline()
            if header.strip().split(",")[:3] != ["cve", "epss", "percentile"]:
                raise UpdateError("the EPSS file does not have the expected columns")
            for rec in csv.reader(fh):
                if len(rec) >= 3 and re.fullmatch(r"CVE-\d{4}-\d{4,}", rec[0]):
                    rows.append((rec[0].upper(), float(rec[1]), float(rec[2]), score_date))
    except (OSError, EOFError, ValueError, gzip.BadGzipFile) as e:
        raise UpdateError(f"the EPSS file could not be read ({e.__class__.__name__})") from None
    if len(rows) < 1000:
        raise UpdateError(f"the EPSS file holds only {len(rows)} scores -- refusing it")
    conn.execute("DELETE FROM epss")
    conn.executemany("INSERT OR REPLACE INTO epss VALUES (?, ?, ?, ?)", rows)
    _set_meta(conn, "epss", rows=len(rows), etag=got.etag, detail=score_date)
    dest.unlink(missing_ok=True)
    return f"{len(rows)} scores ({score_date})"


def nvd_item_cvss(item: dict[str, Any]) -> tuple[str, float, str, str, str] | None:
    """(cve, base score, vector, version, severity) from one NVD 2.0 item: the
    primary CVSS v3.1 score, else v3.0, else v4.0, else v2."""
    cve = item.get("cve") if isinstance(item.get("cve"), dict) else item
    cid = str(cve.get("id") or "")
    if not re.fullmatch(r"CVE-\d{4}-\d{4,}", cid):
        return None
    metrics = cve.get("metrics") if isinstance(cve.get("metrics"), dict) else {}
    for key, version in (("cvssMetricV31", "3.1"), ("cvssMetricV30", "3.0"), ("cvssMetricV40", "4.0"),
                         ("cvssMetricV2", "2.0")):
        entries = [m for m in metrics.get(key) or [] if isinstance(m, dict)]
        if not entries:
            continue
        entries.sort(key=lambda m: 0 if m.get("type") == "Primary" else 1)
        data = entries[0].get("cvssData") or {}
        try:
            score = float(data.get("baseScore"))
        except (TypeError, ValueError):
            continue
        sev = str(data.get("baseSeverity") or entries[0].get("baseSeverity") or "").lower()
        return cid, score, str(data.get("vectorString") or ""), version, sev
    return None


def _nvd_feed(conn: sqlite3.Connection, session: Any, name: str, work: Path) -> int:
    from kratos.adapters.vuln_scan import iter_nvd_feed

    meta_path = work / f"nvd-{name}.meta"
    _fetch(session, NVD_META_URL.format(name=name), meta_path, NVD_META_MAX_BYTES)
    meta = dict(line.split(":", 1) for line in meta_path.read_text(encoding="utf-8", errors="replace").splitlines()
                if ":" in line)
    want_sha = str(meta.get("sha256") or "").strip().lower()
    dest = work / f"nvd-{name}.json.gz"
    _fetch(session, NVD_FEED_URL.format(name=name), dest, NVD_MAX_BYTES)
    sha = hashlib.sha256()
    rows: list[tuple[str, float, str, str, str]] = []

    class _Hashing(io.RawIOBase):
        def __init__(self, inner: Any) -> None:
            self.inner = inner

        def readable(self) -> bool:
            return True

        def readinto(self, b: Any) -> int:
            data = self.inner.read(len(b))
            sha.update(data)
            b[:len(data)] = data
            return len(data)

    try:
        with gzip.open(dest, "rb") as raw:
            text = io.TextIOWrapper(io.BufferedReader(_Hashing(raw), 1 << 20), encoding="utf-8")
            for item in iter_nvd_feed(text):
                got = nvd_item_cvss(item)
                if got:
                    rows.append(got)
            while text.read(1 << 20):
                pass
    except (OSError, EOFError, ValueError, gzip.BadGzipFile) as e:
        raise UpdateError(f"NVD feed {name} could not be read ({e.__class__.__name__})") from None
    if want_sha and sha.hexdigest() != want_sha:
        raise UpdateError(f"NVD feed {name} does not match its published checksum")
    conn.executemany("INSERT OR REPLACE INTO cvss VALUES (?, ?, ?, ?, ?)", rows)
    dest.unlink(missing_ok=True)
    meta_path.unlink(missing_ok=True)
    return len(rows)


def _update_nvd(conn: sqlite3.Connection, session: Any, work: Path, *, full: bool, now: float, log: Log) -> str:
    row = conn.execute("SELECT fetched_at FROM meta WHERE source = 'nvd'").fetchone()
    recent = row is not None and row[0] and now - float(row[0]) < NVD_MODIFIED_WINDOW_DAYS * 86400
    if recent and not full:
        n = _nvd_feed(conn, session, "modified", work)
        total = conn.execute("SELECT COUNT(*) FROM cvss").fetchone()[0]
        _set_meta(conn, "nvd", rows=total, detail="modified feed")
        return f"{n} recently changed scores"
    year = datetime.fromtimestamp(now, timezone.utc).year
    n = 0
    for y in range(NVD_FIRST_YEAR, year + 1):
        log(f"  NVD {y} ...")
        n += _nvd_feed(conn, session, str(y), work)
    total = conn.execute("SELECT COUNT(*) FROM cvss").fetchone()[0]
    _set_meta(conn, "nvd", rows=total, detail=f"yearly feeds {NVD_FIRST_YEAR}-{year}")
    return f"{n} scores from the yearly feeds"


# --------------------------------------------------------------------------- meta helpers
def _meta_etag(conn: sqlite3.Connection, source: str) -> str:
    row = conn.execute("SELECT etag FROM meta WHERE source = ?", (source,)).fetchone()
    has_rows = conn.execute(f"SELECT 1 FROM {source} LIMIT 1").fetchone() if source in ("kev", "epss") else True
    return (row[0] or "") if row and has_rows else ""


def _set_meta(conn: sqlite3.Connection, source: str, *, rows: int, etag: str = "", detail: str = "",
              last_modified: str = "") -> None:
    conn.execute("INSERT OR REPLACE INTO meta (source, fetched_at, etag, last_modified, rows, detail) "
                 "VALUES (?, ?, ?, ?, ?, ?)", (source, time.time(), etag, last_modified, rows, detail))


def _touch_meta(conn: sqlite3.Connection, source: str) -> None:
    conn.execute("UPDATE meta SET fetched_at = ? WHERE source = ?", (time.time(), source))


# --------------------------------------------------------------------------- the update
def resolve_selectors(data_dir: Path, requested: Iterable[str] | None) -> list[Selector]:
    """The releases to hold: those asked for, else every release Kratos has seen in a
    package inventory, plus whatever the current index already holds."""
    if requested:
        return sorted({parse_selector(s) for s in requested}, key=lambda s: s.key)
    keys: set[str] = set()
    from kratos.pkgvuln import inventory_store

    keys.update(inventory_store.known_selectors(data_dir))
    keys.update(_index.held_selectors(data_dir))
    out = []
    for k in sorted(keys):
        try:
            out.append(parse_selector(k))
        except ValueError:
            continue
    return out


def run_update(data_dir: Path, *, selectors: Iterable[str] | None = None, full: bool = False,
               session: Any = None, log: Log | None = None, now: float | None = None) -> UpdateResult:
    """Build a new index and swap it in. Never raises for a download or data
    problem: the result says what happened, and on failure the previous index is
    untouched."""
    log = log or (lambda _msg: None)
    started = time.monotonic()
    data_dir = Path(data_dir)
    try:
        sels = resolve_selectors(data_dir, selectors)
    except ValueError as e:
        return UpdateResult(False, str(e))
    if not sels:
        return UpdateResult(False, "Kratos doesn't know any machine's distribution yet. Run a check on a machine "
                                   "first (its package inventory says which data to download), or name releases "
                                   "with --ecosystems, e.g. --ecosystems ubuntu:22.04,debian:12.")
    folder = data_dir / _index.DIR_NAME
    folder.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(folder, 0o700)
    except OSError:
        pass
    lock_path = folder / ".update.lock"
    with open(lock_path, "a+") as lock:
        try:
            fcntl.flock(lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            return UpdateResult(False, "another vulnerability-data update is already running")
        try:
            return _build(data_dir, folder, sels, full=full, session=_session(session), log=log,
                          now=time.time() if now is None else now, started=started)
        finally:
            fcntl.flock(lock.fileno(), fcntl.LOCK_UN)


def _build(data_dir: Path, folder: Path, sels: list[Selector], *, full: bool, session: Any, log: Log,
           now: float, started: float) -> UpdateResult:
    final = folder / _index.FILE_NAME
    tmp = folder / (_index.FILE_NAME + ".tmp")
    work = folder / "download.tmp"
    for p in (tmp, Path(str(tmp) + "-journal")):
        p.unlink(missing_ok=True)
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(mode=0o700)
    previous = _index.status(data_dir)
    sources: dict[str, str] = {}
    stale: list[str] = []
    try:
        if previous.present and not full and _index.open_readonly(data_dir) is not None:
            src = sqlite3.connect(f"file:{final}?mode=ro", uri=True)
            dst = sqlite3.connect(tmp)
            with dst:
                src.backup(dst)
            src.close()
            dst.close()
        conn = sqlite3.connect(tmp, isolation_level=None)
        try:
            conn.execute("PRAGMA journal_mode=OFF")
            conn.execute("PRAGMA synchronous=OFF")
            _index.create_schema(conn)
            old_keys = set(previous.selectors) if previous.present and not full else set()
            # releases no longer wanted are dropped
            for top in sorted({s.top for s in sels} | {r[0] for r in conn.execute("SELECT DISTINCT top FROM advisories")}):
                top_sels = [s for s in sels if s.top == top]
                conn.execute("BEGIN")
                try:
                    if not top_sels:
                        _Writer(conn, []).clear_top(top)
                        conn.execute("DELETE FROM meta WHERE source IN (?, ?)", (f"osv:{top}", f"osv-index:{top}"))
                        conn.execute("COMMIT")
                        continue
                    same = {s.key for s in top_sels} <= old_keys
                    msg = _update_osv_incremental(conn, session, top, top_sels, work, log) if same else None
                    if msg is None:
                        msg = _update_osv_full(conn, session, top, top_sels, work, log)
                    conn.execute("COMMIT")
                except BaseException:
                    conn.execute("ROLLBACK")
                    raise
                sources[f"OSV {top}"] = msg
                log(f"  OSV {top}: {msg}")
            conn.execute("DELETE FROM ecosystems WHERE selector NOT IN (%s)" % ",".join("?" * len(sels)),
                         [s.key for s in sels])
            for table in ("ranges", "versions"):
                conn.execute(f"DELETE FROM {table} WHERE ecosystem NOT IN (SELECT id FROM ecosystems)")
            for name, fn in (("KEV", lambda: _update_kev(conn, session, work)),
                             ("EPSS", lambda: _update_epss(conn, session, work)),
                             ("NVD CVSS", lambda: _update_nvd(conn, session, work, full=full, now=now, log=log))):
                conn.execute("BEGIN")
                try:
                    sources[name] = fn()
                    conn.execute("COMMIT")
                except UpdateError as e:
                    conn.execute("ROLLBACK")
                    sources[name] = f"not updated: {e}"
                    stale.append(name)
                except BaseException:
                    conn.execute("ROLLBACK")
                    raise
                log(f"  {name}: {sources[name]}")
            for s in sels:
                n = conn.execute(
                    "SELECT COUNT(DISTINCT r.advisory) FROM ranges r JOIN advisories a ON a.id = r.advisory "
                    "JOIN ecosystems e ON e.id = r.ecosystem WHERE a.precise = 1 AND e.selector = ?",
                    (s.key,)).fetchone()[0]
                conn.execute("INSERT OR REPLACE INTO info (key, value) VALUES (?, ?)",
                             (f"precise_count:{s.key}", json.dumps(int(n))))
            conn.execute("INSERT OR REPLACE INTO info (key, value) VALUES ('built_at', ?)", (json.dumps(now),))
            conn.execute("INSERT OR REPLACE INTO info (key, value) VALUES ('selectors', ?)",
                         (json.dumps([s.key for s in sels]),))
            result = conn.execute("PRAGMA integrity_check").fetchone()
            if not result or result[0] != "ok":
                raise UpdateError("the new index failed SQLite's integrity check")
            conn.execute("VACUUM")
        finally:
            conn.close()
        os.chmod(tmp, 0o600)
        os.replace(tmp, final)
        try:
            dfd = os.open(folder, os.O_RDONLY)
            try:
                os.fsync(dfd)
            finally:
                os.close(dfd)
        except OSError:
            pass
    except UpdateError as e:
        return UpdateResult(False, f"Update failed, the previous vulnerability data is kept: {e}",
                            [s.key for s in sels], time.monotonic() - started, sources=sources)
    except sqlite3.Error as e:
        return UpdateResult(False, f"Update failed, the previous vulnerability data is kept: database error ({e})",
                            [s.key for s in sels], time.monotonic() - started, sources=sources)
    finally:
        for p in (tmp, Path(str(tmp) + "-journal")):
            p.unlink(missing_ok=True)
        shutil.rmtree(work, ignore_errors=True)
    size = final.stat().st_size
    msg = f"Vulnerability data updated for {', '.join(s.key for s in sels)} ({size / 1e6:.1f} MB)."
    if stale:
        msg += f" Not refreshed this time: {', '.join(stale)} (the previous data for them is kept)."
    return UpdateResult(True, msg, [s.key for s in sels], time.monotonic() - started, size, sources, stale)
